"""「読めない」を表す例外の親(統合 1.2.72・構造点検の改善案3)

**読めない(届かない・壊れている・掴まれている)ことを「無い」と取り違えない**(統合 1.2.61 の決まり)。
これまで「読めない」の例外を機能ごとに7通り作っていた(設定・共有の設定・停止のお願い・アクセス権限・発注の履歴など)。
どれも、この `Unreadable` を親に持つ。新しく書くところは `except unreadable.Unreadable` で、どれでも受けられる。

それぞれの例外は**前の親(`OSError` など)もそのまま持つ**(いままでの `except OSError` で受けている所は変わらない)。
"""
from __future__ import annotations


class Unreadable(Exception):
    """読めない。「無い」とは別。受けた側は、書かない・消さない・覚えない(前の中身のまま理由を出す)。"""
